export function buildSeedProducts(now = Date.now()): Product[] {
  return seeds.map(({ daysAgo, ...s }) => {
    const a = assets[s.id] ?? { photos: [], model: null };
    const created = new Date(now - daysAgo * 86400000).toISOString();
    return {
      ...s,
      slug: s.id,
      photos: a.photos,
      model3d: a.model,
      status: s.status ?? 'disponivel',
      featured: s.featured ?? false,
      isNew: s.isNew ?? false,
      tags: s.tags ?? [],
      views: s.views ?? 0,
      createdAt: created,
      updatedAt: created,
    };
  });
}
